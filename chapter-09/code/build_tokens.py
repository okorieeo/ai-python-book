"""Generate tokens.css (web) and tokens.ts (React Native) from one source: tokens.json."""
import json

tokens = json.load(open("tokens.json", encoding="utf-8"))

def css_vars(group: dict, prefix: str, unit: str = "") -> list[str]:
    return [f"  --{prefix}-{name}: {value}{unit};" for name, value in group.items()]

light = css_vars(tokens["color"], "color")
dark = css_vars(tokens["color-dark"], "color")
shared = (
    css_vars(tokens["space"], "space", "px")
    + css_vars(tokens["radius"], "radius", "px")
    + css_vars(tokens["font-size"], "font-size", "px")
)

css = "\n".join([
    "/* GENERATED by build_tokens.py - do not edit by hand */",
    ":root {", *light, *shared, "  color-scheme: light dark;", "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    "  :root:not([data-theme=\"light\"]) {", *["  " + line for line in dark], "  }",
    "}",
    "",
    ":root[data-theme=\"dark\"] {", *dark, "}",
    "",
])
open("tokens.css", "w", encoding="utf-8").write(css)

def camel(name: str) -> str:
    first, *rest = name.split("-")
    return first + "".join(word.capitalize() for word in rest)

def ts_object(group: dict) -> str:
    rows = [f"    {camel(k) if not k.isdigit() else repr(k)}: {json.dumps(v)}," for k, v in group.items()]
    return "{\n" + "\n".join(rows) + "\n  }"

ts = "\n".join([
    "// GENERATED by build_tokens.py - do not edit by hand",
    "export const tokens = {",
    f"  light: {ts_object(tokens['color'])},",
    f"  dark: {ts_object(tokens['color-dark'])},",
    f"  space: {ts_object(tokens['space'])},",
    f"  radius: {ts_object(tokens['radius'])},",
    f"  fontSize: {ts_object(tokens['font-size'])},",
    "} as const;",
    "",
])
open("tokens.ts", "w", encoding="utf-8").write(ts)
print("wrote tokens.css and tokens.ts")
